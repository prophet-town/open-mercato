export function renderRouteRegistryFacadesOutput(
  kind: PageRouteManifestKind,
  entries: RouteManifestShardEntry[],
): RouteManifestShardOutput {
  const typeName = kind === 'backend' ? 'BackendRouteManifestEntry' : 'FrontendRouteManifestEntry'
  const metadataExportName = `${kind}RouteMetadata`
  const shardKeys = entries.map((entry) => kind === 'backend' ? getRouteManifestShardKey('backend', entry.path) : ROOT_SHARD_KEY)
  const content = `// AUTO-GENERATED by mercato generate registry (route facades resolved through registered shards)
import { createRouteManifestShardFacades, type ${typeName} } from '@open-mercato/shared/modules/registry'
import { ${metadataExportName} } from './${kind}-route-metadata.generated'

export const ${kind}RouteRegistryFacades: ${typeName}[] = createRouteManifestShardFacades(${JSON.stringify(kind)}, ${metadataExportName}, ${JSON.stringify(shardKeys)})
`
  return { fileName: `${kind}-route-registry.generated.ts`, content }
}

export function renderRouteMetadataOutput(
  kind: RouteManifestShardKind | PageRouteManifestKind,
  entries: RouteManifestShardEntry[],
): RouteManifestShardOutput {
  const isApi = kind === 'api'
  const typePrefix = kind === 'api' ? 'Api' : kind === 'backend' ? 'Backend' : 'Frontend'
  const manifestType = `${typePrefix}RouteManifestEntry`
  const metadataType = `${typePrefix}RouteMetadataEntry`
  const exportName = `${kind}RouteMetadata`
  const fileName = `${kind}-route-metadata.generated.ts`
  const helperImport = isApi ? '' : 'resolvePageRouteMetadata, '
  const imports = uniqueImports(entries)
  const content = `// AUTO-GENERATED by mercato generate registry (route metadata without component loaders)\nimport { ${helperImport}type ${manifestType} } from '@open-mercato/shared/modules/registry'\n${imports.length ? `${imports.join('\n')}\n` : ''}\nexport type ${metadataType} = Omit<${manifestType}, 'load'>\n\nexport const ${exportName}: ${metadataType}[] = ${renderArray(entries)}\n\nexport default ${exportName}\n`
  return { fileName, content }
}

